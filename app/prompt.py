_KIND_HINT = {
    "str": "текст",
    "list": "список строк",
    "link": "имя в именительном падеже",
    "date": "дата YYYY-MM-DD",
    "datetime": "YYYY-MM-DD или YYYY-MM-DDTHH:mm",
    "md": "MM-DD или YYYY-MM-DD",
    "num": "число",
}


def _field_hint(name: str, spec: Field) -> str:
    if spec.kind == "int":
        return f"{name} (число {int(spec.lo)}-{int(spec.hi)})"
    if spec.kind == "enum":
        return f"{name} ({' | '.join(spec.values)})"
    return f"{name} ({_KIND_HINT[spec.kind]})"


def _type_line(t: schema.TypeSpec) -> str:
    parts = [f"- {t.id} «{t.name}»: {t.when}"]
    if t.kinds:
        parts.append("kind: " + " | ".join(t.kinds))
    if t.statuses:
        parts.append("status: " + " | ".join(t.statuses))
    else:
        parts.append("status не заполняется")
    if t.fields:
        parts.append("fields: " + ", ".join(_field_hint(n, f) for n, f in t.fields.items()))
    return " ;; ".join(parts)


@lru_cache(maxsize=1)
def build_system_prompt() -> str:
    types = "\n".join(_type_line(t) for t in schema.TYPES.values())
    areas = ", ".join(schema.AREAS)
    catalog = (
        "\nТИПЫ ЗАМЕТОК (type — «название»: когда выбирать ;; kind ;; status ;; fields)\n"
        f"{types}\n"
        f"\nСФЕРЫ ЖИЗНИ (area, одна из): {areas}\n"
        f"ПРИОРИТЕТ (priority, только если сказан словами): {', '.join(schema.PRIORITIES)}\n"
        "Общие поля заметки (title, summary, tags, people, related, area, confidence) заполняются у каждой заметки."
    )
    return _PREAMBLE + catalog + _FORMAT
